class SMS_I18n {
    static getLang() {
        return localStorage.getItem('sms_lang') || 'en';
    }

    static setLang(lang) {
        if (['en', 'ur'].includes(lang)) {
            localStorage.setItem('sms_lang', lang);
            this.applyLanguage(lang);
        }
    }

    static __(key, defaultVal = '') {
        const lang = this.getLang();
        if (SMS_TRANSLATIONS[lang] && SMS_TRANSLATIONS[lang][key]) {
            return SMS_TRANSLATIONS[lang][key];
        }
        if (SMS_TRANSLATIONS.en && SMS_TRANSLATIONS.en[key]) {
            return SMS_TRANSLATIONS.en[key];
        }
        return defaultVal || key;
    }

    static applyLanguage(lang) {
        const isRtl = (lang === 'ur');
        document.documentElement.lang = lang;
        document.documentElement.dir = isRtl ? 'rtl' : 'ltr';

        if (isRtl) {
            document.body.classList.add('sms-rtl-mode');
        } else {
            document.body.classList.remove('sms-rtl-mode');
        }

        // Update elements marked with data-i18n
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            const translation = this.__(key);
            if (translation) {
                if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                    if (el.getAttribute('placeholder')) {
                        el.setAttribute('placeholder', translation);
                    }
                } else {
                    el.textContent = translation;
                }
            }
        });

        // Update active class on switchers
        document.querySelectorAll('.sms-lang-btn').forEach(btn => {
            if (btn.getAttribute('data-lang') === lang) {
                btn.classList.add('active');
            } else {
                btn.classList.remove('active');
            }
        });
    }

    static init() {
        const lang = this.getLang();
        this.applyLanguage(lang);

        document.querySelectorAll('.sms-lang-btn').forEach(btn => {
            btn.addEventListener('click', (e) => {
                e.preventDefault();
                const newLang = btn.getAttribute('data-lang');
                if (newLang) {
                    this.setLang(newLang);
                }
            });
        });
    }
}

document.addEventListener('DOMContentLoaded', () => {
    SMS_I18n.init();
});
